#!/usr/bin/env python3
"""Wrap a WebGL/Three.js-style full-screen fragment shader (uniform float
uTime; varying vec2 vUv; gl_FragCoord; gl_FragColor) into a GLSL 4.50
compute shader for vk-play (one XRGB8888 pixel per invocation).

  frag2comp.py FRAGMENT.glsl OUT.comp [TIME_SCALE]

TIME_SCALE multiplies vk-play's seconds into uTime (Three.js demos often
advance uTime per frame, e.g. 0.003 per frame at 60 fps = 0.18 per second).
"""
import re
import sys

src = open(sys.argv[1]).read()
scale = float(sys.argv[3]) if len(sys.argv) > 3 else 1.0

src = re.sub(r'^\s*uniform\s+float\s+uTime\s*;', '', src, flags=re.M)
src = re.sub(r'^\s*varying\s+vec2\s+vUv\s*;', '', src, flags=re.M)
src = re.sub(r'^\s*precision\s+\w+\s+float\s*;', '', src, flags=re.M)
src = re.sub(r'\bvoid\s+main\s*\(\s*\)', 'void frag_main()', src)
src = src.replace('gl_FragColor', 'g_frag_color').replace('gl_FragCoord', 'g_frag_coord')

head = f'''#version 450
// Generated by frag2comp.py from {sys.argv[1].split("/")[-1]}
layout(local_size_x = 64) in;
layout(set = 0, binding = 0) buffer Out {{ uint px[]; }};
layout(push_constant) uniform P {{ float time; uint width; uint height; }};

float uTime;
vec2 vUv;
vec4 g_frag_coord;
vec4 g_frag_color;
'''
tail = f'''
void main()
{{
   uint x = gl_WorkGroupID.x * 64u + gl_LocalInvocationID.x;
   uint y = gl_WorkGroupID.y;
   uTime = time * {scale!r};
   g_frag_coord = vec4(float(x) + 0.5, float(height - y) - 0.5, 0.0, 1.0);
   vUv = g_frag_coord.xy / vec2(float(width), float(height));
   frag_main();
   uvec3 c = uvec3(clamp(g_frag_color.rgb, 0.0, 1.0) * 255.0 + 0.5);
   px[y * width + x] = 0xff000000u | (c.r << 16) | (c.g << 8) | c.b;
}}
'''
open(sys.argv[2], 'w').write(head + src + tail)
