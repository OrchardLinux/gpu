#!/usr/bin/env python3
"""Fragment-shader op tests for the A10 compiler: each test is a GLSL
expression over the vertex colour v = (0.25, 0.5, 0.75, 1.0) (the same at
every vertex, vk-tri TRI_VCOL, so nothing folds) and the colour it must give.

  fsops.py OUT_DIR    # writes OUT_DIR/fsops/NAME.spv and OUT_DIR/fsops/run.sh

then, in the device chroot: sh run.sh (vk-tri on PATH) prints PASS/FAIL per test.
"""
import math
import pathlib
import subprocess
import sys

V = (0.25, 0.5, 0.75, 1.0)
TESTS = {
    'mul': ('vec4(v.r * 2.0, v.g * v.g, v.b * 0.5, v.a)', (0.5, 0.25, 0.375, 1)),
    'add': ('vec4(v.r + 0.5, v.g - 0.25, v.b + v.r - 0.5, v.a)', (0.75, 0.25, 0.5, 1)),
    'fma': ('vec4(fma(v.r, v.g, v.b) - 0.5, fma(v.g, v.g, v.r), fma(v.b, 2.0, -1.0), 1.0)',
            (0.375, 0.5, 0.5, 1)),
    'rcp': ('vec4(1.0 / (v.r * 8.0), 0.25 / v.g, v.r / v.b, 1.0)', (0.5, 0.5, 1 / 3, 1)),
    'floor': ('vec4(fract(v.b * 3.0), floor(v.b * 2.0) * 0.5, ceil(v.r) * 0.75, 1.0)',
              (0.25, 0.5, 0.75, 1)),
    'sqrt': ('vec4(sqrt(v.r), inversesqrt(v.a * 4.0), sqrt(v.g * 0.5), 1.0)', (0.5, 0.5, 0.5, 1)),
    'exp': ('vec4(exp2(-v.a), log2(v.a * 2.0) * 0.5, pow(v.r, 0.5), 1.0)', (0.5, 0.5, 0.5, 1)),
    'sin': ('vec4(sin(v.r * 2.0), cos(v.g), sin(v.b) * 0.5 + 0.5, 1.0)',
            (math.sin(0.5), math.cos(0.5), math.sin(0.75) * 0.5 + 0.5, 1)),
    'select': ('vec4(v.r < v.g ? v.b : v.r, v.b > v.a ? 1.0 : 0.0, v.g >= 0.5 ? 1.0 : 0.25, 1.0)',
               (0.75, 0, 1, 1)),
    'minmax': ('vec4(max(v.r, v.g), min(v.b, v.g), clamp(v.b * 2.0, 0.0, 0.9), 1.0)',
               (0.5, 0.5, 0.9, 1)),
    'int': ('vec4(float(i + 2) / 16.0, float(i * 3) / 36.0, float(i >> 1) / 6.0, float((i & 3) | 8) / 10.0)',
            (0.5, 0.5, 0.5, 1)),
    'abs': ('vec4(abs(v.r - 0.75), -(v.r - 0.75), sign(v.r - 0.5) * -0.5, 1.0)', (0.5, 0.5, 0.5, 1)),
    'vec': ('vec4(dot(v.rg, v.rg), length(v.rg * vec2(1.2, 0.8)), normalize(v.bb).x, 1.0)',
            (0.3125, 0.5, math.sqrt(0.5), 1)),
    'smooth': ('vec4(smoothstep(0.0, 1.0, v.g), step(0.5, v.r), mix(v.r, v.b, 0.5), 1.0)',
               (0.5, 0, 0.5, 1)),
    'branch': ('b', (0.75, 0.25, 0.5, 1)),
}
BRANCH = '''
	vec4 o_ = vec4(0.0, 0.0, 0.0, 1.0);
	if (v.r < 0.3) {
		o_.r = v.b;
		o_.g = v.r;
	} else {
		o_.r = 0.1;
	}
	for (int k = 0; k < i; k++)
		o_.b += 1.0 / 12.0;
	o = o_;
'''


def pixel(c):
    b = [min(255, max(0, int(x * 255 + 0.5))) for x in c]
    return '0x%02x%02x%02x%02x' % (b[3], b[0], b[1], b[2])


def main(out):
    d = pathlib.Path(out).resolve() / 'fsops'
    d.mkdir(parents=True, exist_ok=True)
    lines = ['#!/bin/sh', '# generated by fsops.py', 'cd "$(dirname "$0")"', 'PATH=/usr/local/bin:$PATH pass=0 fail=0',
             'export PVR_I_WANT_A_BROKEN_VULKAN_DRIVER=1 TRI_VCOL=%s' % ','.join(map(str, V))]
    for name, (expr, want) in TESTS.items():
        body = BRANCH if expr == 'b' else '\to = %s;\n' % expr
        (d / f'{name}.frag').write_text(
            '#version 450\nlayout(location = 0) in vec4 v;\nlayout(location = 0) out vec4 o;\n'
            'void main()\n{\n\tint i = int(v.b * 8.0);\n' + body + '}\n')
        lines.append(f'r=$(TRI_FS_SPV={name}.spv TRI_WANT={pixel(want)} timeout -k 5 20 vk-tri 2>&1)')
        lines.append(f'case "$r" in *PASS*) pass=$((pass + 1)); echo "{name}: PASS";; '
                     f'*) fail=$((fail + 1)); echo "{name}: FAIL (want {pixel(want)}):"; '
                     'echo "$r" | grep corner | head -1;; esac')
    lines.append('echo "$pass passed, $fail failed"')
    (d / 'run.sh').write_text('\n'.join(lines) + '\n')
    subprocess.run(['podman', 'run', '--rm', '-v', f'{d}:/d', 'localhost/orchard-mesa-g9p:trixie', 'sh', '-c',
                    'for s in /d/*.frag; do glslangValidator -V -o ${s%.frag}.spv $s >/dev/null || '
                    '{ glslangValidator -V -o /dev/null $s; exit 1; }; done'], check=True)


if __name__ == '__main__':
    main(sys.argv[1])
