#!/usr/bin/env python3
"""Generate PDS probe plans; no USC tasks and no device access by this tool.

Based on the locally pinned Mesa Rogue XML/encoder reference. Profiles 50–52
were subsequently tested: all stalled, with no fault/crash or completion.
Hook 46 remains the working baseline. No G9P PDS/USC ISA compatibility claim.
This is standalone experiment tooling, not a Mesa change.
"""

import argparse
import json
import struct


MESA_COMMIT = "1c3a936490f9f0951188218e136cd03bca497386"
HALT = 0xd3000000
DOUTC = 0xf0000005
# BRA !IF1, KEEP, +2: skip the coefficient-update task's HALT.
SKIP_COEFFICIENT_TASK = 0xc2c00002
# ADD64 unsigned const64[0], const64[0] -> persistent temp64[0].
CLEAR_BARRIER = 0x80000010
TERMINATE = 0x80000000
PDS_HEAP = 0x300000000
PDS_SCRATCH = 0x84000
GPU_PAGE_SIZE = 0x4000


def kernel_words(*, code_offset, data_offset, data_chunks=1, fence=False,
                 shared=False, dependency="none", target="any", max_instances=8,
                 groups=(1, 1, 1), local=(1, 1, 1), one_wg=False):
    """Pack direct Rogue KERNEL0/1/2/3/4/5/8; offsets, not absolute VAs."""
    if code_offset < 0 or data_offset < 0 or (code_offset | data_offset) & 15:
        raise ValueError("PDS offsets must be nonnegative and 16-byte aligned")
    if code_offset >= 1 << 32 or data_offset >= 1 << 32:
        raise ValueError("PDS offset exceeds the register field")
    if not 1 <= data_chunks <= 63:
        raise ValueError("use at least one data chunk so the PDS program runs")
    if dependency not in ("none", "pds", "usc") or target not in ("all", "any"):
        raise ValueError("unknown dependency or USC target")
    if not 1 <= max_instances <= 32:
        raise ValueError("instance count must be 1..32 (32 encodes as zero)")
    if len(groups) != 3 or any(not 1 <= v <= 1 << 32 for v in groups):
        raise ValueError("global groups must have three positive u32-plus-one counts")
    if len(local) != 3 or any(not 1 <= v <= 512 for v in local):
        raise ValueError("local dimensions must have three counts in 1..512")
    k0 = data_chunks << 2 | (target == "any") << 1 | bool(fence)
    k1 = data_offset | {"none": 0, "pds": 1, "usc": 2}[dependency] << 2 | bool(shared) << 1
    k2 = code_offset | bool(one_wg)
    k8 = (max_instances % 32) << 27 | (local[0] - 1) << 18 | (local[1] - 1) << 9 | (local[2] - 1)
    return [k0, k1, k2, *(v - 1 for v in groups), k8]


def probe_plan(name):
    profiles = {
        "fence": (50, 0x1000, 0x800,
                  [SKIP_COEFFICIENT_TASK, HALT, CLEAR_BARRIER, DOUTC, HALT],
                  dict(fence=True, dependency="pds", target="any")),
        "empty": (51, 0x2000, 0xa00,
                  [SKIP_COEFFICIENT_TASK, HALT, CLEAR_BARRIER, HALT],
                  dict(shared=True, dependency="none", target="all")),
        "short-fence": (52, 0x3000, 0xe00, [DOUTC, HALT],
                        dict(fence=True, dependency="pds", target="any")),
    }
    if name not in profiles:
        raise ValueError(f"unknown probe {name}")
    number, code, data, program, flags = profiles[name]
    # Only use the existing owned, read-only PDS page from hook 37.
    if code + len(program) * 4 + 64 > GPU_PAGE_SIZE or data + 16 > GPU_PAGE_SIZE:
        raise ValueError("probe escapes the existing mapped PDS page or guard")
    if max(code, data) < min(code + len(program) * 4, data + 16):
        raise ValueError("PDS code overlaps constants")
    stream = kernel_words(code_offset=code, data_offset=data, **flags) + [TERMINATE]
    return {
        "name": name,
        "candidate_hook": number,
        "hardware_tested": True,
        "hardware_completed": False,
        "hardware_observation": "stalled; zero completion stamps; no MMU fault or firmware crash",
        "scope": "PDS-only candidate; NO USC shader or shader-result claim",
        "reference_commit": MESA_COMMIT,
        "code_offset": code,
        "data_offset": data,
        "code_gpu_va": hex(PDS_HEAP + code),
        "data_gpu_va": hex(PDS_HEAP + data),
        "code_scratch_offset": PDS_SCRATCH + code,
        "data_scratch_offset": PDS_SCRATCH + data,
        "pds_words": program,
        "cdm_words": stream,
        "flags": flags,
    }


def render_hook(name):
    p = probe_plan(name)
    lines = [
        "#!/bin/busybox sh",
        f"# TESTED: incomplete probe {p['candidate_hook']}: {name}, PDS only, NO USC shader.",
        "# Generated by tools/pds_probe.py; keep hook 46 as the working baseline.",
        "# Hardware: zero stamps, no MMU fault/crash; execution/completion not proven.",
        ". /run/agx-init46.sh",
        "# Use fresh 4 KiB code offsets, not the repeatedly reused code offset 0.",
        "# This reduces a cache-reuse confound; it is NOT proof of cache coherency.",
    ]
    for i, word in enumerate(p["pds_words"]):
        lines.append(f"put32 scratch 0x{p['code_scratch_offset'] + i * 4:x} 0x{word:08x}")
    for i in range(4):
        lines.append(f"put32 scratch 0x{p['data_scratch_offset'] + i * 4:x} 0")
    lines.append("# Direct 1x1x1 kernel; minimum data, no ordinary temp/USC allocation.")
    for i, word in enumerate(p["cdm_words"]):
        lines.append(f"put32 scratch 0x{0x60000 + i * 4:x} 0x{word:08x}")
    return "\n".join(lines) + "\n"


def pds_bytes(name):
    words = probe_plan(name)["pds_words"]
    return struct.pack(f"<{len(words)}I", *words)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("plan", "hook"))
    parser.add_argument("profile", choices=("fence", "empty", "short-fence"))
    args = parser.parse_args()
    if args.mode == "plan":
        print(json.dumps(probe_plan(args.profile), indent=2))
    else:
        print(render_hook(args.profile), end="")


if __name__ == "__main__":
    main()
